package rroyo.jge.enums;

/**
 * The {@code SpriteHorizontalDirection} enum defines the horizontal orientation
 * a graphical element or sprite can face within the game.
 */
public enum SpriteHorizontalDirection {

    /**
     * Indicates the sprite is facing towards the left.
     */
    LEFT,

    /**
     * Indicates the sprite is facing towards the right.
     */
    RIGHT
}
